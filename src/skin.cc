/* **************************** is_joint_unique **************************** */

bool
is_joint_unique (const IndexHelper &helper, const std::vector<int> &joints,
                 size_t i)
{
  if (i >= helper.nodes_size ())
    return true;

  size_t cnt = 0;

  for (auto it : joints)
    {
      if (joints[i] == it)
        cnt++;
    }

  return cnt <= 1;
}

