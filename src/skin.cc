/* **************************** GLTFSkin::create *************************** */

std::shared_ptr<GLTFSkin>
GLTFSkin::create (const IndexHelper &helper, const std::string &name,
                  const std::optional<int> &inverse_bind_matrices,
                  const std::optional<int> &skeleton,
                  const std::vector<int> &joints)
{
  std::shared_ptr<GLTFSkin> tmp (new GLTFSkin (name));

  size_t shifted_accessor_index;
  size_t shifted_node_index;

  if (inverse_bind_matrices == std::nullopt)
    {
      // NOTE : glTF 2.0 5.28.1 demand that empty inverseBindMatrices must
      // produce identity matrices. Identity matrices will be generated by
      // loader itself.
      tmp->m_inverse_bind_matrices = std::nullopt;
    }
  else
    {
      shifted_accessor_index
          = helper.accessor_defaults_size () + inverse_bind_matrices.value ();
      if (inverse_bind_matrices < 0)
        {
          std::cout << "[W] glTF 2.0 5.28.1: skin.inverseBindMatrices >= 0"
                    << std::endl;
          return nullptr;
        }
      else if (shifted_accessor_index >= helper.accessors_size ())
        {
          std::cout << "[W] glTF 2.0 5.28.1: skin.inverseBindMatrices is out "
                       "of bounds"
                    << std::endl;
          return nullptr;
        }
      else
        {
          if ((helper.accessor (shifted_accessor_index)->count ()
               < joints.size ())
              || (helper.accessor (shifted_accessor_index)->type ()
                  != GLTFAccessorType::mat4)
              || (helper.accessor (shifted_accessor_index)->component_type ()
                  != GLTFComponentType::ffloat))
            {
              std::cout << "[W] glTF 2.0 5.28.1: skin.inverseBindMatrices "
                           "must point to an accessor with N matrices 4x4, "
                           "where N > joints.count"
                        << std::endl;
              return nullptr;
            }
        }
      tmp->m_inverse_bind_matrices = shifted_accessor_index;
    }

  if (skeleton == std::nullopt)
    {
      std::cout
          << "[W] glTF 2.0: undefined skin.skeleton is not supported for "
          << PACKAGE << " " << VERSION << std::endl;
      return nullptr;
    }
  else
    {
      shifted_node_index = helper.node_defaults_size () + skeleton.value ();

      if (skeleton < 0)
        {
          std::cout << "[W] glTF 2.0 5.28.2: skin.skeleton >= 0" << std::endl;
          return nullptr;
        }
      else if (shifted_node_index >= helper.nodes_size ())
        {
          std::cout << "[W] glTF 2.0 5.28.2: skin.skeleton is out of bounds"
                    << std::endl;
          return nullptr;
        }
      else
        {
          tmp->m_skeleton = shifted_node_index;
        }
    }

  if (joints.empty ())
    {
      std::cout << "[W] glTF 2.0 5.28.3: skin.joints is empty" << std::endl;
      return nullptr;
    }
  else
    {
      for (size_t i = 0; i < joints.size (); i++)
        {
          if (joints[i] < 0)
            {
              std::cout << "[W] glTF 2.0 5.28.3: skin.joints[" << i << "] >= 0"
                        << std::endl;
              return nullptr;
            }

          if (!is_joint_unique (helper, joints, i))
            {
              std::cout << "[W] glTF 2.0 5.28.3: skin.joints[" << i
                        << "] is not unique" << std::endl;
              return nullptr;
            }

          if (!helper.is_indirect_parent (joints[i]
                                              + helper.node_defaults_size (),
                                          tmp->m_skeleton.value ()))
            {
              std::cout << "[W] glTF 2.0 5.28.2: skin.skeleton must be common "
                           "direct or indirect parent of all joints"
                        << std::endl;
              return nullptr;
            }
        }
      for (auto it : joints)
        {
          tmp->m_joints.push_back (helper.node_defaults_size () + it);
        }
    }

  return tmp;
}

